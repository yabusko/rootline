const SUPPORTED = ['en', 'ru'];
const LS_LANG = 'family-tree-lang';
let lang = 'en';
try {
  const saved = localStorage.getItem(LS_LANG);
  if (SUPPORTED.includes(saved)) lang = saved;
  else if (/^ru\b/i.test(navigator.language || '')) lang = 'ru';
} catch (e) { /* storage unavailable */ }

function t(key, vars) {
  let s = STRINGS[lang][key];
  if (s === undefined) s = STRINGS.en[key];
  if (s === undefined) return key;
  if (vars) s = s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] === undefined || vars[k] === null ? '' : String(vars[k])));
  return s;
}

/* "3 people" / "3 человека". Forms are separated by "|" in the dictionary: EN has one|many, RU has one|few|many. */
function count(n, key) {
  const forms = t(key).split('|');
  let form;
  if (lang === 'ru' && forms.length >= 3) {
    const a = n % 10, b = n % 100;
    form = a === 1 && b !== 11 ? forms[0] : a >= 2 && a <= 4 && (b < 12 || b > 14) ? forms[1] : forms[2];
  } else form = n === 1 ? forms[0] : forms[forms.length - 1];
  return `${n} ${form}`;
}

/* Cyrillic → Latin (simplified BGN/PCGN, plus Ukrainian/Belarusian letters). Display only. */
const TRANSLIT = {
  а: 'a', б: 'b', в: 'v', г: 'g', д: 'd', е: 'e', ё: 'yo', ж: 'zh', з: 'z', и: 'i', й: 'y', к: 'k', л: 'l', м: 'm',
  н: 'n', о: 'o', п: 'p', р: 'r', с: 's', т: 't', у: 'u', ф: 'f', х: 'kh', ц: 'ts', ч: 'ch', ш: 'sh', щ: 'shch',
  ъ: '', ы: 'y', ь: '', э: 'e', ю: 'yu', я: 'ya',
  і: 'i', ї: 'yi', є: 'ye', ґ: 'g', ў: 'u',
};
const CYR_RE = /[Ѐ-ӿ]/;
function translit(s, force) {
  if (!s) return s;
  if (!force && lang !== 'en') return s;
  s = String(s);
  if (!CYR_RE.test(s)) return s;
  let out = '';
  for (let i = 0; i < s.length; i++) {
    const ch = s[i], low = ch.toLowerCase();
    const m = TRANSLIT[low];
    if (m === undefined) { out += ch; continue; }
    if (ch === low) { out += m; continue; }
    // Upper-case letter: capitalise the first Latin letter; use all caps when the next letter is upper-case too (e.g. "ЩЕ" → "SHCHE").
    const next = s[i + 1];
    const allCaps = next !== undefined && next !== next.toLowerCase() && next === next.toUpperCase();
    out += allCaps ? m.toUpperCase() : m.charAt(0).toUpperCase() + m.slice(1);
  }
  return out;
}

/* Static markup: <el data-i18n="key"> sets textContent; <el data-i18n-attr="placeholder:key,aria-label:key2"> sets attributes. */
function applyStatic(root) {
  root = root || document;
  document.documentElement.lang = lang;
  for (const el of root.querySelectorAll('[data-i18n]')) el.textContent = t(el.dataset.i18n);
  for (const el of root.querySelectorAll('[data-i18n-attr]')) {
    for (const pair of el.dataset.i18nAttr.split(',')) {
      const i = pair.indexOf(':'); if (i < 0) continue;
      el.setAttribute(pair.slice(0, i).trim(), t(pair.slice(i + 1).trim()));
    }
  }
  for (const b of root.querySelectorAll('[data-lang]')) b.setAttribute('aria-pressed', String(b.dataset.lang === lang));
}

function setLang(code) {
  if (!SUPPORTED.includes(code) || code === lang) return;
  lang = code;
  try { localStorage.setItem(LS_LANG, code); } catch (e) { /* storage unavailable */ }
  applyStatic();
  document.dispatchEvent(new CustomEvent('languagechange', { detail: { lang } }));
}

window.i18n = { t, count, translit, applyStatic, setLang, SUPPORTED, get lang() { return lang; } };
